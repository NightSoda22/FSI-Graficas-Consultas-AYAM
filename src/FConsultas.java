    private void BPromedioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BPromedioActionPerformed
        String promedio_mensual = "SELECT CONCAT(`año`, '-', mes) AS periodo, ROUND(glucosa_prom, 1) AS promedio\n"
                + "FROM promedio_mensual\n"
                + "WHERE curp = 'ausl120130a'\n"
                + "ORDER BY `año`, mes";

        datos = cnx.consultar(promedio_mensual);
        System.out.println("Datos: " + datos);

        series.clear();
        series.add("promedio");

        PGrafica.removeAll();
        PGrafica.setLayout(new java.awt.BorderLayout());
        chart = new GraficaXY("Promedio mensual de glucosa", "Mes", "Glucosa (mg/dL)", series, datos);
        PGrafica.add(chart.chartPanel, java.awt.BorderLayout.CENTER);
        PGrafica.revalidate();
        PGrafica.repaint();

        cnx.entablar(promedio_mensual, TConsultas, 50, 50);
    }//GEN-LAST:event_BPromedioActionPerformed

